
import React, { useState, useRef } from 'react';
import { OnboardingInfo, AdminDocument, View } from '../types';
import { DocumentIcon, UploadIcon, ZipIcon, CheckSquareIcon, PlusIcon, DeleteIcon, CheckCircleIcon, TinyLockIcon, DownloadIcon, CalendarIcon, EditIcon } from './Icons';
import { OnboardingInfoFormModal } from './OnboardingInfoFormModal';

interface EssentialsViewProps {
  profileId: string;
  onboardingInfo: OnboardingInfo;
  view: View;
  documents: AdminDocument[];
  onUpdateDocuments: (docs: AdminDocument[]) => void;
  // Note: we might need a way to trigger info update from here if we want direct edit
  // For now we'll assume App handles the modal trigger or we pass an onUpdateInfo
  onUpdateInfo?: (info: OnboardingInfo) => void;
}

// Extended interface locally to handle the security token logic
interface EquipmentItem {
    id: string;
    item: string;
    serial: string;
    status: 'pending' | 'ready_for_pickup' | 'signed';
    deliveryCode?: string; // The secret code generated by admin
}

const initialEquipment: EquipmentItem[] = [
    { id: 'eq-1', item: 'Notebook Corporativa', serial: 'CN-0X89-7483-222', status: 'pending' },
    { id: 'eq-2', item: 'Monitor Externo 24"', serial: 'DELL-24-992', status: 'pending' },
    { id: 'eq-3', item: 'Periféricos (Mouse/Teclado)', serial: 'N/A', status: 'pending' },
];

export const EssentialsView: React.FC<EssentialsViewProps> = ({ profileId, onboardingInfo, view, documents, onUpdateDocuments, onUpdateInfo }) => {
  const [equipment, setEquipment] = useState<EquipmentItem[]>(initialEquipment);
  const [isInfoModalOpen, setIsInfoModalOpen] = useState(false);
  
  // Admin State
  const [newDocTitle, setNewDocTitle] = useState('');
  const [newDocRequired, setNewDocRequired] = useState(true);

  // User State for verification
  const [verificationCodes, setVerificationCodes] = useState<Record<string, string>>({});
  const [errorMessages, setErrorMessages] = useState<Record<string, string>>({});

  const fileInputRef = useRef<HTMLInputElement>(null);
  const [uploadingDocId, setUploadingDocId] = useState<string | null>(null);

  // Role Determination
  const isGlobalAdmin = view === 'admin';
  const isLeader = view === 'leader';
  const isNewHire = view === 'newHire';
  const isManagementView = isGlobalAdmin || isLeader;

  // --- ACTIONS ---

  const handleUploadClick = (id: string) => {
      setUploadingDocId(id);
      if (fileInputRef.current) {
          fileInputRef.current.click();
      }
  };

  const handleFileChange = (e: React.ChangeEvent<HTMLInputElement>) => {
    if (e.target.files && e.target.files.length > 0 && uploadingDocId) {
        const file = e.target.files[0];
        const currentUploadingDocId = uploadingDocId;
        const reader = new FileReader();

        reader.onload = () => {
        const result = reader.result;

        if (typeof result !== 'string') return;

        onUpdateDocuments(
            documents.map((doc) =>
            doc.id === currentUploadingDocId
                ? {
                    ...doc,
                    status: 'uploaded',
                    uploadedAt: new Date().toISOString(),
                    fileName: file.name,
                    fileUrl: result,
                }
                : doc
            )
        );
        };

        reader.readAsDataURL(file);
        setUploadingDocId(null);
    }

    if (fileInputRef.current) {
        fileInputRef.current.value = '';
    }
    };

  const handleGenerateCode = (id: string) => {
      const code = Math.floor(1000 + Math.random() * 9000).toString();
      setEquipment(prev => prev.map(eq => 
          eq.id === id ? { ...eq, status: 'ready_for_pickup', deliveryCode: code } : eq
      ));
  };

  const handleCodeInputChange = (id: string, value: string) => {
      setVerificationCodes(prev => ({ ...prev, [id]: value }));
      if (errorMessages[id]) {
          setErrorMessages(prev => {
              const newErrors = { ...prev };
              delete newErrors[id];
              return newErrors;
          });
      }
  };

  const handleVerifyAndSign = (id: string, actualCode?: string) => {
      const inputCode = verificationCodes[id];
      if (inputCode === actualCode) {
          setEquipment(prev => prev.map(eq => eq.id === id ? { ...eq, status: 'signed' } : eq));
          setVerificationCodes(prev => { const n = {...prev}; delete n[id]; return n; });
      } else {
          setErrorMessages(prev => ({ ...prev, [id]: 'Código incorrecto' }));
      }
  };

  const handleAddDocument = () => {
      if (!newDocTitle.trim()) return;
      const newDoc: AdminDocument = {
          id: `doc-${Date.now()}`,
          title: newDocTitle,
          status: 'pending',
          required: newDocRequired
      };
      onUpdateDocuments([...documents, newDoc]);
      setNewDocTitle('');
      setNewDocRequired(true);
  };

  const handleDeleteDocument = (id: string) => {
      onUpdateDocuments(documents.filter(d => d.id !== id));
  };

  const handleVerifyDocument = (id: string) => {
      onUpdateDocuments(documents.map(doc => 
          doc.id === id ? { 
              ...doc, 
              status: 'verified', 
              verifiedAt: new Date().toISOString() 
          } : doc
      ));
  };

  const formatDateTime = (isoString?: string) => {
      if (!isoString) return '';
      return new Date(isoString).toLocaleString('es-ES', { 
          day: '2-digit', month: '2-digit', hour: '2-digit', minute: '2-digit' 
      });
  };

  const formatDateShort = (dateString?: string) => {
      if (!dateString) return 'No establecida';
      return new Date(dateString + 'T00:00:00').toLocaleDateString('es-ES', { 
          day: '2-digit', month: '2-digit', year: 'numeric' 
      });
  };

  const isOverdue = (deadline?: string) => {
      if (!deadline) return false;
      const now = new Date();
      now.setHours(0,0,0,0);
      return new Date(deadline + 'T00:00:00') < now;
  };

  const progress = documents.length > 0 
    ? Math.round((documents.filter(d => d.status === 'verified').length / documents.length) * 100)
    : 0;

  return (
    <div className="max-w-5xl mx-auto space-y-8 pb-12">
        <input type="file" ref={fileInputRef} className="hidden" onChange={handleFileChange} />
        
        <div className="bg-white p-8 rounded-lg shadow-sm border border-slate-200 flex flex-col md:flex-row justify-between items-center gap-6 relative overflow-hidden">
            {/* Decoration for management view */}
            {isManagementView && <div className="absolute top-0 left-0 w-1 h-full bg-brand-cyan" />}
            
            <div className="flex-1">
                <h2 className="text-2xl font-bold text-slate-800 font-heading">
                    {isManagementView ? `Legajo de ${onboardingInfo.newHireName}` : 'Mi Legajo Digital'}
                </h2>
                <div className="flex flex-col sm:flex-row sm:items-center gap-4 mt-2">
                    <p className="text-slate-500 text-sm">
                        {isManagementView 
                            ? 'Supervisa y valida la documentación administrativa obligatoria.' 
                            : 'Completa tu documentación antes de tu primer día.'}
                    </p>
                    
                    <div className={`inline-flex items-center gap-2 px-3 py-1.5 rounded-full text-xs font-bold border transition-colors ${
                        isOverdue(onboardingInfo.documentationDeadline) && progress < 100
                        ? 'bg-red-50 text-red-700 border-red-200' 
                        : 'bg-brand-cyan/10 text-brand-cyan border-brand-cyan/30'
                    }`}>
                        <CalendarIcon />
                        <span>VENCIMIENTO: {formatDateShort(onboardingInfo.documentationDeadline)}</span>
                        {isGlobalAdmin && (
                            <button 
                                onClick={() => setIsInfoModalOpen(true)}
                                className="ml-1 p-0.5 hover:bg-brand-cyan/20 rounded text-brand-cyan transition-colors"
                                title="Cambiar fecha de vencimiento"
                            >
                                <EditIcon />
                            </button>
                        )}
                        {isOverdue(onboardingInfo.documentationDeadline) && progress < 100 && (
                            <span className="ml-2 animate-pulse text-red-600">⚠️ ATRASADO</span>
                        )}
                    </div>
                </div>
            </div>

            <div className="flex items-center gap-4">
                 <div className="text-right">
                    <p className="text-sm font-medium text-slate-600">Progreso</p>
                    <p className="text-2xl font-bold text-brand-cyan">{progress}%</p>
                </div>
                <div className="w-16 h-16 rounded-full bg-slate-100 flex items-center justify-center border-4 border-brand-cyan overflow-hidden relative">
                    <div 
                      className="absolute bottom-0 left-0 w-full bg-brand-cyan transition-all duration-1000" 
                      style={{ height: `${progress}%` }}
                    />
                    <span className="relative z-10 text-[10px] font-bold text-slate-800">{progress}%</span>
                </div>
            </div>
        </div>

        <div className="grid grid-cols-1 lg:grid-cols-2 gap-8">
            <div className="bg-white p-6 rounded-lg shadow-sm border border-slate-200 flex flex-col h-full">
                <div className="flex justify-between items-center mb-6">
                    <h3 className="text-lg font-semibold text-slate-800 font-heading">Documentación</h3>
                </div>
                
                <div className="space-y-4 flex-grow">
                    {documents.map(doc => (
                        <div key={doc.id} className={`flex flex-col p-4 rounded-lg border transition-all ${doc.status === 'verified' ? 'bg-emerald-50 border-emerald-200 shadow-sm' : 'bg-white border-slate-200'}`}>
                            <div className="flex items-start justify-between gap-3">
                                <div className="flex items-start gap-3 flex-1 min-w-0">
                                    <div className={`mt-1 p-2 rounded-full flex-shrink-0 ${doc.status === 'verified' ? 'bg-emerald-200 text-emerald-700' : doc.status === 'uploaded' ? 'bg-brand-cyan/20 text-brand-cyan' : 'bg-slate-100 text-slate-400'}`}>
                                        <DocumentIcon />
                                    </div>
                                    <div className="min-w-0 flex-1">
                                        <p className="font-bold text-slate-800 text-sm">{doc.title}</p>
                                        <div className="flex items-center gap-2 mt-1 flex-wrap">
                                            {doc.required && <span className="text-[10px] font-bold bg-slate-200 text-slate-600 px-1.5 py-0.5 rounded uppercase tracking-tighter">Requerido</span>}
                                            {doc.status === 'pending' && <span className="text-[10px] text-slate-400 uppercase font-bold">Pendiente</span>}
                                            {doc.status === 'uploaded' && <span className="text-[10px] text-brand-cyan font-bold uppercase tracking-tighter">En revisión ({formatDateTime(doc.uploadedAt)})</span>}
                                            {doc.status === 'verified' && <span className="text-[10px] text-emerald-600 font-bold uppercase tracking-tighter">Aprobado ({formatDateTime(doc.verifiedAt)})</span>}
                                        </div>
                                        {doc.fileName && (
                                            <div className="flex items-center gap-2 mt-2">
                                              <p className="text-xs text-slate-500 truncate italic" title={doc.fileName}>
                                                  {doc.fileName}
                                              </p>
                                              {isManagementView && doc.fileUrl && (
                                                <a 
                                                  href={doc.fileUrl} 
                                                  download={doc.fileName}
                                                  className="p-1 text-brand-cyan hover:bg-brand-cyan/20 rounded transition-colors"
                                                  title="Descargar para revisar"
                                                >
                                                  <DownloadIcon />
                                                </a>
                                              )}
                                            </div>
                                        )}
                                    </div>
                                </div>

                                <div className="flex flex-col gap-2 items-end">
                                    {isGlobalAdmin ? (
                                        <>
                                            {doc.status === 'uploaded' && (
                                                <button 
                                                    onClick={() => handleVerifyDocument(doc.id)}
                                                    className="flex items-center gap-1 text-xs font-bold bg-emerald-600 text-white px-3 py-1.5 rounded-md hover:bg-emerald-700 transition-colors shadow-sm"
                                                >
                                                    <CheckSquareIcon /> Validar
                                                </button>
                                            )}
                                            {doc.status === 'verified' && <CheckCircleIcon className="text-emerald-500" />}
                                            <button onClick={() => handleDeleteDocument(doc.id)} className="text-slate-300 hover:text-red-500 p-1"><DeleteIcon /></button>
                                        </>
                                    ) : (
                                        <>
                                            {doc.status === 'verified' ? (
                                                <CheckCircleIcon className="text-emerald-500" />
                                            ) : doc.status === 'uploaded' ? (
                                                <span className="text-[10px] font-bold text-brand-cyan bg-brand-cyan/10 px-2 py-1 rounded border border-brand-cyan/30">EN REVISIÓN</span>
                                            ) : (
                                                isNewHire ? (
                                                    <button onClick={() => handleUploadClick(doc.id)} className="flex items-center gap-1 text-xs bg-brand-cyan text-white px-3 py-1.5 rounded-md hover:bg-brand-cyan/80 transition-colors shadow-sm">
                                                        <UploadIcon /> Subir
                                                    </button>
                                                ) : (
                                                    <span className="text-[10px] font-bold text-slate-300 uppercase">Esperando carga</span>
                                                )
                                            )}
                                        </>
                                    )}
                                </div>
                            </div>
                        </div>
                    ))}
                </div>

                {isGlobalAdmin && (
                    <div className="mt-6 pt-4 border-t border-slate-100">
                        <p className="text-[10px] font-bold text-slate-400 mb-2 uppercase tracking-widest">Añadir Requisito</p>
                        <div className="flex gap-2 items-center">
                            <input type="text" value={newDocTitle} onChange={(e) => setNewDocTitle(e.target.value)} placeholder="Ej: Título Analítico" className="flex-grow text-sm rounded-md border-slate-300 focus:ring-brand-cyan" />
                            <button onClick={handleAddDocument} className="p-2 bg-slate-800 text-white rounded-md hover:bg-slate-900 transition-colors"><PlusIcon /></button>
                        </div>
                    </div>
                )}
            </div>

            <div className="bg-white p-6 rounded-lg shadow-sm border border-slate-200 flex flex-col h-full">
                 <div className="flex justify-between items-center mb-6">
                    <h3 className="text-lg font-semibold text-slate-800 font-heading">Entrega de Equipamiento</h3>
                 </div>
                 
                 <div className="space-y-4 flex-grow">
                    {equipment.map(eq => (
                        <div key={eq.id} className="p-4 border border-slate-100 rounded-lg bg-slate-50">
                            <div className="flex justify-between items-start mb-2">
                                <div>
                                    <p className="font-bold text-slate-800 text-sm">{eq.item}</p>
                                    <p className="text-[10px] text-slate-400 font-mono">S/N: {eq.serial}</p>
                                </div>
                                {eq.status === 'signed' && (
                                     <span className="text-[10px] bg-emerald-100 text-emerald-700 px-2 py-1 rounded-full font-bold flex items-center gap-1 border border-emerald-200">
                                        <CheckCircleIcon /> RECIBIDO
                                    </span>
                                )}
                            </div>
                            
                            <div className="mt-3 pt-3 border-t border-slate-200">
                                {eq.status === 'signed' ? (
                                    <p className="text-[10px] text-slate-500 font-medium">Equipamiento verificado mediante firma digital segura.</p>
                                ) : (
                                    <>
                                    {isGlobalAdmin ? (
                                        <div className="w-full">
                                            {eq.status === 'pending' ? (
                                                <button onClick={() => handleGenerateCode(eq.id)} className="w-full text-xs font-bold bg-slate-800 text-white px-3 py-2 rounded shadow-sm hover:bg-slate-700 transition-colors flex items-center justify-center gap-2">
                                                    <TinyLockIcon /> Iniciar Entrega (Generar PIN)
                                                </button>
                                            ) : (
                                                <div className="bg-brand-cyan text-white rounded p-3 flex flex-col items-center">
                                                    <span className="text-[10px] uppercase font-bold tracking-tighter opacity-80">Dictar PIN al ingresante</span>
                                                    <span className="text-3xl font-mono font-black tracking-[0.5em] my-1">{eq.deliveryCode}</span>
                                                </div>
                                            )}
                                        </div>
                                    ) : isNewHire ? (
                                        <div className="w-full">
                                            {eq.status === 'ready_for_pickup' ? (
                                                <div className="space-y-2">
                                                    <label className="text-[10px] font-bold text-brand-cyan uppercase">PIN DE RECEPCIÓN:</label>
                                                    <div className="flex gap-2">
                                                        <input type="text" maxLength={4} className="w-20 text-center font-mono text-xl font-bold rounded-md border-slate-300" value={verificationCodes[eq.id] || ''} onChange={(e) => handleCodeInputChange(eq.id, e.target.value)} />
                                                        <button onClick={() => handleVerifyAndSign(eq.id, eq.deliveryCode)} className="flex-1 bg-brand-cyan text-white text-xs font-bold rounded-md shadow-sm" disabled={!verificationCodes[eq.id]}>CONFIRMAR</button>
                                                    </div>
                                                </div>
                                            ) : (
                                                <div className="flex items-center gap-2 text-amber-600 bg-amber-50 px-3 py-2 rounded text-xs font-bold border border-amber-100">
                                                    <TinyLockIcon /> ESPERANDO ENTREGA FÍSICA
                                                </div>
                                            )}
                                        </div>
                                    ) : (
                                        <span className="text-[10px] font-bold text-slate-400 uppercase italic">Pendiente de gestión administrativa</span>
                                    )}
                                    </>
                                )}
                            </div>
                        </div>
                    ))}
                 </div>
                 
                 {!isGlobalAdmin && (
                     <div className="mt-6 pt-6 border-t border-slate-100">
                        <button className="w-full flex items-center justify-center gap-2 bg-slate-900 text-white py-3 rounded-xl font-bold hover:bg-black transition-all shadow-xl shadow-slate-200">
                            <ZipIcon />
                            EXPORTAR LEGAJO (ZIP)
                        </button>
                        <p className="text-center text-[10px] font-bold text-slate-400 mt-3 uppercase tracking-widest">Apto para auditoría y contabilidad</p>
                     </div>
                 )}
            </div>
        </div>

        <OnboardingInfoFormModal 
            profileId={profileId}
            isOpen={isInfoModalOpen} 
            onClose={() => setIsInfoModalOpen(false)} 
            onSubmit={(i) => {
                onUpdateInfo?.(i);
                setIsInfoModalOpen(false);
            }} 
            infoData={onboardingInfo} 
        />
    </div>
  );
};
